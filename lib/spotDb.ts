/** 目的地にマッチする実在スポット一覧（なければ null） */
export function areaSpots(destination: string): string[] | null {
  const d = destination || '';
  for (const a of AREAS) {
    if (a.match.some((m) => d.includes(m))) return a.spots;
  }
  return null;
}

/** マッチしない地域向けの控えめなフォールバック（目的地名＋一般的な施設種別） */
export function fallbackSpots(destination: string): string[] {
  const base = (destination || 'この地域').trim();
  return [`${base}城`, `${base}の中心商店街`, `${base}の市場・朝市`, `${base}総合公園`, `${base}の郷土資料館`];
}
